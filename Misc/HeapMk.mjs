import {readFileSync,writeFileSync} from "node:fs";
import {compileHolyC} from "../src/compiler.js";
import {HEAP_BASE,DATA_BASE} from "../src/abi.js";

const source="#define HEAP_START "+HEAP_BASE+"\n"+
  readFileSync(new URL("../Kernel/Heap.HH",import.meta.url),"utf8")+
  readFileSync(new URL("../Kernel/Heap.HC",import.meta.url),"utf8");
let output="// Generated by Misc/HeapMk.mjs from Kernel/Heap.HC. Do not edit.\n";
for (const shared of [false,true]) {
  const result=compileHolyC(source,{noPrelude:true,lenient:false,
    memory:{imported:true,shared,initial:257,maximum:shared?65536:null},
    exports:["HeapAlloc","HeapFree","HeapSize","HeapCursor","HeapCtrlNew","HeapCtrlDel","HeapCtrlTrim",
      "HeapOwn","HeapCtrlCnt","HeapCtrlFirst","HeapBP"]});
  if (result.warnings.length || result.dataEnd!==DATA_BASE ||
      WebAssembly.Module.imports(new WebAssembly.Module(result.bytes))
        .some(item=>item.kind!=="memory"))
    throw new Error("Heap must have no static storage or host function imports");
  output+="export const "+(shared?"SHARED":"UNSHARED")+"="+
    JSON.stringify(Buffer.from(result.bytes).toString("base64"))+";\n";
}
const target=new URL("../src/runtime/heap-code.js",import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target,"utf8")!==output)
    throw new Error("Heap module is stale; run npm run generate");
  console.log("HolyC heap and compiled modules match.");
} else writeFileSync(target,output);
